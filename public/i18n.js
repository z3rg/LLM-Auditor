const LANG_NAMES = { id: 'Bahasa Indonesia', en: 'English' };
const UI_LANG_KEY = 'llm-auditor-lang';
const QUIZ_LANG_KEY = 'llm-auditor-quiz-lang';

function readPref(key, allowed, fallback) {
  try { const v = localStorage.getItem(key); if (allowed.includes(v)) return v; } catch (_) {}
  return fallback;
}
function writePref(key, value) {
  try { localStorage.setItem(key, value); } catch (_) { /* mode privat: berlaku untuk tab ini saja */ }
}

const i18n = {
  lang: readPref(UI_LANG_KEY, ['id', 'en'], 'id'),
  quizPref: readPref(QUIZ_LANG_KEY, ['auto', 'id', 'en'], 'auto'),
  listeners: [],
};

/** Terjemahkan kunci; {nama} diganti dari `vars`. Kunci yang hilang jatuh ke Bahasa Indonesia, lalu ke kunci itu sendiri. */
function t(key, vars) {
  let s = (I18N[i18n.lang] && I18N[i18n.lang][key]) ?? I18N.id[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));
  return s;
}

/** Bahasa soal kuis yang efektif ('id' | 'en'). */
function quizLang() { return i18n.quizPref === 'auto' ? i18n.lang : i18n.quizPref; }
/** Locale untuk tanggal/angka. */
function locale() { return i18n.lang === 'en' ? 'en-GB' : 'id-ID'; }

function applyI18n(root = document) {
  document.documentElement.lang = i18n.lang;
  root.querySelectorAll('[data-i18n]').forEach((n) => { n.textContent = t(n.dataset.i18n); });
  root.querySelectorAll('[data-i18n-html]').forEach((n) => { n.innerHTML = t(n.dataset.i18nHtml); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((n) => { n.placeholder = t(n.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-aria-label]').forEach((n) => { n.setAttribute('aria-label', t(n.dataset.i18nAriaLabel)); });
  root.querySelectorAll('.lang-switch button[data-lang]').forEach((b) => {
    const on = b.dataset.lang === i18n.lang;
    b.classList.toggle('is-active', on);
    b.setAttribute('aria-pressed', String(on));
  });
  root.querySelectorAll('#uiLangSelect').forEach((s) => { s.value = i18n.lang; });
  root.querySelectorAll('.quiz-lang-select').forEach((s) => { s.value = i18n.quizPref; });
}

function setUiLang(lang) {
  if (!I18N[lang] || lang === i18n.lang) return;
  i18n.lang = lang;
  writePref(UI_LANG_KEY, lang);
  applyI18n();
  i18n.listeners.forEach((fn) => { try { fn(lang); } catch (_) {} });
}
function setQuizLang(pref) {
  if (!['auto', 'id', 'en'].includes(pref)) return;
  i18n.quizPref = pref;
  writePref(QUIZ_LANG_KEY, pref);
  applyI18n();
  i18n.listeners.forEach((fn) => { try { fn(i18n.lang, 'quiz'); } catch (_) {} });
}
/** Daftarkan fungsi yang menggambar ulang tampilan dinamis saat bahasa berubah. */
function onLangChange(fn) { i18n.listeners.push(fn); }

document.addEventListener('DOMContentLoaded', () => {
  applyI18n();
  document.querySelectorAll('.lang-switch button[data-lang]').forEach((b) =>
    b.addEventListener('click', () => setUiLang(b.dataset.lang)));
  document.querySelectorAll('#uiLangSelect').forEach((s) =>
    s.addEventListener('change', () => setUiLang(s.value)));
  document.querySelectorAll('.quiz-lang-select').forEach((s) =>
    s.addEventListener('change', () => setQuizLang(s.value)));
});
